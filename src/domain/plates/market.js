function roundRub(n){
  const v = Math.max(1000, Math.round(n));
  if(v >= 1000000) return Math.round(v / 10000) * 10000;
  if(v >= 100000) return Math.round(v / 1000) * 1000;
  if(v >= 10000) return Math.round(v / 100) * 100;
  return Math.round(v / 50) * 50;
}

function ruDigit(d){
  if(!d || d.length !== 3) return { rub: 4500, name: 'обычные цифры' };
  if(d === '777' || d === '888' || d === '999') return { rub: 190000, name: 'тройка '+d };
  if(d === '000') return { rub: 240000, name: 'нули 000' };
  if(/^00[1-9]$/.test(d)) return { rub: 260000, name: 'первые номера '+d };
  if(d === '007' || d === '077' || d === '700' || d === '070') return { rub: 280000, name: 'комбинация '+d };
  if(/^(\d)\1\1$/.test(d)) return { rub: 110000, name: 'тройка '+d };
  if(/^(100|200|300|400|500|600|700|800|900)$/.test(d)) return { rub: 62000, name: 'круглое '+d };
  if('123,321,234,432,345,543,456,654,567,765,678,876,789,987'.split(',').includes(d)) return { rub: 78000, name: 'лесенка '+d };
  if(d[0] === d[2] && d[0] !== d[1]) return { rub: 52000, name: 'зеркало '+d };
  if(d[0] === d[1] || d[1] === d[2]) return { rub: 24000, name: 'пара '+d };
  return { rub: 4500, name: 'обычные цифры' };
}

function ruRegionMult(code){
  return RU_REGION_MULT[code] || 1;
}

function appraiseRU(plate){
  const m = String(plate || '').match(/^([А-ЯЁ])(\d{3})([А-ЯЁ]{2})\s(\d{2,3})$/);
  if(!m) return { price: 4500, line: 'Российский номер' };
  const series = m[1] + m[3];
  const digit = ruDigit(m[2]);
  let price = digit.rub;
  const same = m[1] === m[3][0] && m[3][0] === m[3][1];
  const tailSame = m[3][0] === m[3][1];
  const elite = !!SERIES_NOTE[series] || ['АМР','ЕКХ','СКР','ХКХ','АОО','ВОО','МОО','СОО','ООО','ААА','МММ'].includes(series);
  if(same) price *= price < 30000 ? 4.2 : 6.2;
  else if(tailSame) price *= 1.85;
  if(elite && !same) price *= 5.2;
  if(elite && (m[2] === '777' || m[2] === '001' || m[2] === '007' || m[2] === '000') && ruRegionMult(m[4]) >= 2.4) price *= 1.85;
  price *= ruRegionMult(m[4]);
  const place = RU_REGION[m[4]] || ('код '+m[4]);
  const seriesText = SERIES_NOTE[series] || (same ? 'одинаковые буквы '+series : tailSame ? 'пара букв '+m[3] : 'серия '+series);
  return { price: roundRub(price), line: place+' · '+digit.name+' · '+seriesText };
}

function fourDigit(d){
  if(!d || d.length !== 4) return { rub: 4000, name: 'обычные цифры' };
  if(d === '0001' || d === '0007') return { rub: 180000, name: 'первые номера '+d };
  if(/^000[1-9]$/.test(d)) return { rub: 140000, name: 'первые номера '+d };
  if(/^(\d)\1\1\1$/.test(d)) return { rub: d === '7777' || d === '8888' || d === '9999' ? 160000 : 90000, name: 'четверка '+d };
  if(/^(1000|2000|3000|4000|5000|6000|7000|8000|9000)$/.test(d)) return { rub: 48000, name: 'круглое '+d };
  if(d === '1234' || d === '4321') return { rub: 42000, name: 'лесенка '+d };
  if(d[0] === d[3] && d[1] === d[2]) return { rub: 36000, name: 'зеркало '+d };
  return { rub: 4000, name: 'обычные цифры' };
}

function appraiseBY(plate){
  const m = String(plate || '').match(/^(\d{4})\s([А-ЯІ]{2})-(\d)$/);
  if(!m) return { price: 2500, line: 'Белорусский номер' };
  const digit = fourDigit(m[1]);
  let price = digit.rub * 0.5;
  if(m[2] === 'МВ') price *= 3.4;
  else if(m[2][0] === m[2][1]) price *= 2.1;
  if(m[3] === '7') price *= 1.8;
  const series = m[2] === 'МВ' ? 'серия МВ, минский «ведомственный» тип' : 'серия '+m[2];
  const city = m[3] === '7' ? 'Минск' : 'регион '+m[3];
  return { price: roundRub(price), line: city+' · '+digit.name+' · '+series };
}

function appraiseUA(plate){
  const m = String(plate || '').match(/^([А-ЯІ]{2})\s(\d{4})\s([А-ЯІ]{2})$/);
  if(!m) return { price: 3000, line: 'Украинский номер' };
  const digit = fourDigit(m[2]);
  let price = digit.rub * 0.58;
  if(m[1] === m[3] && m[1][0] === m[1][1]) price *= 2.6;
  else if(m[1] === 'АА' || m[3] === 'АА') price *= 1.7;
  else if(m[1][0] === m[1][1]) price *= 1.5;
  const where = m[1] === 'АА' ? 'Киев АА' : 'серия '+m[1];
  return { price: roundRub(price), line: where+' · '+digit.name };
}

function appraiseCN(plate){
  const m = String(plate || '').match(/^(.)([A-Z])\s(\d{5})$/);
  if(!m) return { price: 8000, line: 'Китайский номер' };
  const eights = (m[3].match(/8/g) || []).length;
  const fours = (m[3].match(/4/g) || []).length;
  let price = 8000;
  let name = 'обычные цифры';
  if(/^(\d)\1\1\1\1$/.test(m[3])){
    price = m[3][0] === '8' ? 1500000 : m[3][0] === '6' ? 900000 : 520000;
    name = 'пятёрка '+m[3];
  } else if(eights >= 4){
    price = 420000 + eights * 180000;
    name = eights+' восьмёрок';
  } else if(eights >= 2){
    price = 48000 + eights * 36000;
    name = eights+' восьмёрки';
  } else if(m[3] === '00001' || m[3] === '10001'){
    price = 380000;
    name = 'первые номера';
  }
  if(fours && eights < 4) price *= Math.max(0.45, 1 - fours * 0.12);
  price *= CN_MULT[m[1]] || 1;
  if(m[2] === 'A') price *= 1.35;
  const city = CN_NAME[m[1]] || 'провинция';
  return { price: roundRub(price), line: city+' · литера '+m[2]+' · '+name };
}

function appraiseUS(plate){
  const m = String(plate || '').match(/^([A-Z]+)\s(\d{4})$/);
  if(!m) return { price: 8000, line: 'Американский vanity' };
  const word = m[1];
  let price = 9000;
  let name = 'обычный набор букв';
  if(word.length <= 3 && word[0] === word[1] && word[1] === word[2]){
    price = 70000;
    name = 'одинаковые буквы';
  } else if(US_WORD[word]){
    price = 140000 * US_WORD[word];
    name = 'слово '+word;
  } else if(word.length >= 4 && word.length <= 8 && /^[A-Z]+$/.test(word) && !/[0-9]/.test(word)){
    price = 90000 + Math.max(0, 8 - word.length) * 25000;
    name = 'слово '+word;
  }
  if(m[2] === '0001' || m[2] === '0007') price *= 1.8;
  else if(/^(\d)\1\1\1$/.test(m[2])) price *= 1.45;
  return { price: roundRub(price), line: 'США · '+name+' · цифры '+m[2] };
}

export function appraisePlate(plate, flag, region, rarity){
  const found = flag === 'ru' ? appraiseRU(plate)
    : flag === 'by' ? appraiseBY(plate)
    : flag === 'ua' ? appraiseUA(plate)
    : flag === 'cn' ? appraiseCN(plate)
    : flag === 'us' ? appraiseUS(plate)
    : { price: RMAP[rarity]?.price || 4500, line: 'Номер' };
  const country = COUNTRY[flag] || 1;
  const floor = Math.round((FLOOR[rarity] || FLOOR.common) * country);
  return { price: Math.max(found.price, floor), line: found.line };
}

export function describePlate(plate, flag, region, rarity){
  return appraisePlate(plate, flag, region, rarity).line;
}

